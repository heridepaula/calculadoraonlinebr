import { Transform } from "node:stream";

import type { AppLoadContext, EntryContext } from "@remix-run/node";
import { createReadableStreamFromReadable } from "@remix-run/node";
import { RemixServer } from "@remix-run/react";
import { isbot } from "isbot";
import { renderToPipeableStream } from "react-dom/server";

const ABORT_DELAY = 5_000;

/**
 * O renderToPipeableStream do React 18 às vezes deixa bytes 0x00 extras no HTML quando um
 * caractere de vários bytes (acento, emoji) cai na fronteira do buffer interno: o texto fica
 * intacto, mas com NUL no meio ("taxa b<NUL>ásica"). UTF-8 válido nunca tem 0x00, então
 * removê-los é seguro. Afetava 12 páginas em produção em nov/2026; seo:check acusa regressão.
 */
function createHtmlBody(): Transform {
  return new Transform({
    transform(chunk: Buffer, _encoding, callback) {
      if (chunk.indexOf(0) === -1) {
        callback(null, chunk);
        return;
      }
      const clean = Buffer.allocUnsafe(chunk.length);
      let length = 0;
      for (const byte of chunk) {
        if (byte !== 0) clean[length++] = byte;
      }
      callback(null, clean.subarray(0, length));
    },
  });
}

export default function handleRequest(
  request: Request,
  responseStatusCode: number,
  responseHeaders: Headers,
  remixContext: EntryContext,
  // This is ignored so we can keep it in the template for visibility.  Feel
  // free to delete this parameter in your app if you're not using it!
  // eslint-disable-next-line @typescript-eslint/no-unused-vars
  loadContext: AppLoadContext
) {
  return isbot(request.headers.get("user-agent") || "")
    ? handleBotRequest(request, responseStatusCode, responseHeaders, remixContext)
    : handleBrowserRequest(request, responseStatusCode, responseHeaders, remixContext);
}

function handleBotRequest(
  request: Request,
  responseStatusCode: number,
  responseHeaders: Headers,
  remixContext: EntryContext
) {
  return new Promise((resolve, reject) => {
    let shellRendered = false;
    const { pipe, abort } = renderToPipeableStream(
      <RemixServer context={remixContext} url={request.url} abortDelay={ABORT_DELAY} />,
      {
        onAllReady() {
          shellRendered = true;
          const body = createHtmlBody();
          const stream = createReadableStreamFromReadable(body);

          responseHeaders.set("Content-Type", "text/html");
          responseHeaders.set("Vary", "Accept-Encoding");

          resolve(
            new Response(stream, {
              headers: responseHeaders,
              status: responseStatusCode,
            })
          );

          pipe(body);
        },
        onShellError(error: unknown) {
          reject(error);
        },
        onError(error: unknown) {
          responseStatusCode = 500;
          // Log streaming rendering errors from inside the shell.  Don't log
          // errors encountered during initial shell rendering since they'll
          // reject and get logged in handleDocumentRequest.
          if (shellRendered) {
            console.error(error);
          }
        },
      }
    );

    setTimeout(abort, ABORT_DELAY);
  });
}

